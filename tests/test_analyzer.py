"""Tests for parsing, cause analysis, review flags, report export and the updater.

Run:  python -m unittest discover -s tests -v

The sample files (sample_files/, generated by scripts/make_samples.py) are made-up
events with known answers. Real relay files: put scrubbed copies in
tests/fixtures/<case-name>/ with an expected.json (see tests/fixtures/README.md);
every case folder is picked up automatically by RealFileCases.
"""
import hashlib
import io
import json
import os
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

import sel_trip_analyzer as app  # noqa: E402

SAMPLES = os.path.join(ROOT, "sample_files")
FIXTURES = os.path.join(HERE, "fixtures")


def load(*names):
    paths = app.expand_paths([os.path.join(SAMPLES, n) for n in names] if names else [SAMPLES])
    return app.load_files(paths) + (paths,)


def analyze(name, *more):
    """Analyze the first event in a sample file the way the report does."""
    events, rdb, err, paths = load(name, *more)
    e = next(x for x in events if x.kind in ("event", "history"))
    s_rdb, label, how = app.match_settings(e, rdb)
    return e, app.analyze_event(e, {**e.settings, **s_rdb}, how, label)


def text(a):
    return "\n".join(a["cause"] + a["checks"] + a["gaps"])


