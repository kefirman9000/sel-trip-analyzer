class Settings(unittest.TestCase):
    @unittest.skipIf(app.olefile is None, "olefile not installed")
    def test_rdb_ole(self):
        rdb = app.parse_rdb(os.path.join(SAMPLES, "Feeder12_settings.rdb"))
        s = rdb["FEEDER 12"]
        self.assertEqual(s["LL"], "10.00")
        self.assertIn("Z1G", s["TR"])
        self.assertEqual(s["__method__"], "ole")

    def test_rdb_text_fallback(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "x.rdb")
            with open(p, "wb") as f:
                f.write(b"\x00\x01junk RID     =FEEDER 12\nTR      =M1P + Z1G\nLL      =10.00\n")
            s = app.parse_rdb(p)["FEEDER 12"]
            self.assertEqual((s["TR"], s["LL"], s["__method__"]), ("M1P + Z1G", "10.00", "scan"))

    def test_rdb_not_applied_to_other_relay(self):
        rec = app.EventRecord(source="x", relay_id="LINE 5")
        s, label, how = app.match_settings(rec, {"FEEDER 12": {"RID": "FEEDER 12", "TR": "Z1G"}})
        self.assertEqual((s, how), ({}, "mismatch"))

    def test_rdb_assumed_when_no_relay_id(self):
        rec = app.EventRecord(source="x")
        s, label, how = app.match_settings(rec, {"FEEDER 12": {"RID": "FEEDER 12", "TR": "Z1G"}})
        self.assertEqual((label, how), ("FEEDER 12", "assumed"))

    def test_negated_terms_ignored(self):
        self.assertEqual(app.equation_hits("Z1G AND NOT 50P1 + !51G", ["50P1", "51G", "Z1G"]), ["Z1G"])


