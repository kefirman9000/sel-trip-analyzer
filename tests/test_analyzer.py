class CausesAndFlags(unittest.TestCase):
    def test_clean_zone1_fault(self):
        e, a = analyze("Feeder12_AG_Zone1.cev", "Feeder12_settings.rdb")
        self.assertTrue(a["tripped"])
        self.assertEqual(a["primary"], ["Z1G"])
        self.assertEqual((a["checks"], a["gaps"]), ([], []))
        self.assertEqual(a["confidence"], "High")

    def test_pott_trip_explained_by_trcomm(self):
        e, a = analyze("Line5_BC_Zone2_POTT.cev")
        self.assertIn("M2P", a["primary"])
        self.assertIn("PTRX", a["primary"])
        self.assertIn("communications-assisted trip", text(a))
        self.assertEqual(a["checks"], [])

    def test_inconsistent_record_is_flagged(self):
        e, a = analyze("Feeder9_AG_needs_review.cev")
        t = text(a)
        for want in ("Targets show phase(s) B but the event type says A",
                     "Highest fault current is on phase B",
                     "beyond the end of the line",
                     "cycles to open after the trip"):
            self.assertIn(want, t)
        self.assertEqual(a["confidence"], "Low")

    def test_transfer_trip(self):
        e, a = analyze("Feeder7_transfer_trip.sum")
        self.assertIn("transfer trip", text(a))
        self.assertTrue(any("without identifying a fault type" in c for c in a["checks"]))

    def test_underfrequency(self):
        e, a = analyze("Feeder14_underfrequency.txt", "Feeder12_settings.rdb")
        t = text(a)
        self.assertIn("58.85 Hz, well off nominal 60 Hz", t)
        self.assertIn("none match relay 'FEEDER 14'", t)       # Feeder 12 settings NOT applied

    def test_eve_uses_residual_ground_not_neutral_ct(self):
        e, a = analyze("Feeder3_CG_51G.eve")
        self.assertFalse(any("ground current" in c for c in a["checks"]), a["checks"])

    def test_history_rows(self):
        events, rdb, err, paths = load("Feeder12_history.his", "Feeder12_settings.rdb")
        rows = {e.event_type: e for e in events if e.kind == "history"}
        def run(e):
            s, label, how = app.match_settings(e, rdb)
            return text(app.analyze_event(e, {**e.settings, **s}, how, label))
        self.assertIn("beyond the end of the line", run(rows["ABC T"]))
        self.assertIn("behind the relay", run(rows["CG T"]))
        self.assertIn("History row only", run(rows["AG T"]))
        self.assertNotIn("CHECK", run(rows["ER"]))

    def test_history_row_linked_to_cev(self):
        events, rdb, err, paths = load("Feeder12_history.his", "Feeder12_AG_Zone1.cev", "Feeder12_settings.rdb")
        report = app.build_report(events, rdb, err, paths)
        self.assertIn("Same event as #", report)
        self.assertNotIn("History row only", report.split("Same event as")[1].split("Event ")[0])


