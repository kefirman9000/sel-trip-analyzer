class ReportAndExport(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        events, rdb, err, paths = load()
        cls.text = app.build_report(events, rdb, err, paths, "Crew found a cracked insulator.")

    def test_report_sections(self):
        for h in ("QUICK SUMMARY", "EVENT DETAILS", "ANALYST COMMENTS / NOTES", "Crew found",
                  "Needs review:", "CHECK:", "Confidence  :", "SEQUENTIAL EVENTS RECORDER"):
            self.assertIn(h, self.text)

    def test_events_sorted_by_time(self):
        qs = [ln for ln in self.text.splitlines() if ln[:3].strip().rstrip(".").isdigit() and " | " in ln]
        self.assertIn("09/30/26", qs[0])
        self.assertIn("10/27", qs[-1])

    def test_blocks(self):
        blocks = app.parse_report_text(self.text)
        self.assertEqual(blocks[0][0], "title")
        qs = next(b for b in blocks if b[0] == "table" and b[1][0] == "#")
        self.assertEqual(len(qs[2]), 11)
        seq = next(b for b in blocks if b[0] == "table" and b[1][0] == "Cycle")
        self.assertTrue(any(r[1] == "TRIP" for r in seq[2]))
        self.assertTrue(any(b[0] == "bullets" and any(x.startswith("CHECK:") for x in b[1]) for b in blocks))

    def test_docx_keeps_user_edits(self):
        from docx import Document
        edited = self.text.replace("QUICK SUMMARY", "QUICK SUMMARY\nEdited by hand: confirmed with dispatch.")
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "r.docx")
            app.export_report(edited, p)
            doc = Document(p)
            body = "\n".join(par.text for par in doc.paragraphs)
            cells = "\n".join(c.text for t in doc.tables for r in t.rows for c in r.cells)
        self.assertIn("Edited by hand: confirmed with dispatch.", body)
        self.assertIn("CHECK:", body)
        self.assertIn("FEEDER 12", cells)

    def test_pdf(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "r.pdf")
            app.export_report(self.text, p)
            with open(p, "rb") as f:
                data = f.read()
        self.assertTrue(data.startswith(b"%PDF"))
        self.assertGreater(len(data), 5000)

    def test_garbage_text_still_exports(self):
        junk = "just some notes\n\nNOT A REPORT\n  weird : line\n    - bullet?"
        with tempfile.TemporaryDirectory() as d:
            for ext in (".docx", ".pdf", ".txt"):
                app.export_report(junk, os.path.join(d, "j" + ext))


class ViewOptions(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.events, cls.rdb, cls.err, cls.paths = load()

    def view(self, **opts):
        _, shown, n_dups = app.prepare_view(self.events, self.rdb, opts)
        return shown, n_dups

    def test_filters(self):
        self.assertEqual(len(self.view()[0]), 11)
        self.assertTrue(all(it["a"]["tripped"] for it in self.view(show="trips")[0]))
        self.assertEqual([it["e"].event_type for it in self.view(show="notrip")[0]], ["ER"])
        review = self.view(show="review")[0]
        self.assertTrue(review and all(it["a"]["checks"] or it["a"]["gaps"] for it in review))
        self.assertTrue(all(app.event_core(it["e"].event_type) in app.FAULT_TYPES for it in self.view(show="faults")[0]))
        self.assertTrue(all(app.relay_key(it["e"]) == "FEEDER 12" for it in self.view(relay="feeder 12")[0]))
        self.assertEqual([it["e"].source for it in self.view(search="ptrx")[0]], ["Line5_BC_Zone2_POTT.cev"])
        self.assertEqual(len(self.view(search="pott")[0]), 2)     # the POTT trip + the COMM-target transfer trip

    def test_duplicates_hidden(self):
        shown, n = self.view(hide_duplicates=True)
        self.assertEqual((len(shown), n), (10, 1))
        self.assertFalse(any(it["e"].dup_of is not None for it in shown))

    def test_sorts(self):
        oldest = [it["order"] for it in self.view()[0]]
        self.assertEqual(oldest, sorted(oldest))
        newest = self.view(sort="newest")[0]
        self.assertEqual([it["order"] for it in newest], sorted(oldest, reverse=True))
        relays = [app.relay_key(it["e"]).upper() for it in self.view(sort="relay")[0]]
        self.assertEqual(relays, sorted(relays))
        counts = [len(it["a"]["checks"]) + len(it["a"]["gaps"]) for it in self.view(sort="review")[0]]
        self.assertEqual(counts, sorted(counts, reverse=True))

    def test_report_states_the_view(self):
        text = app.build_report(self.events, self.rdb, self.err, self.paths, "",
                                {"show": "trips", "relay": "FEEDER 12", "hide_duplicates": True, "detail": "summary"})
        self.assertIn("Showing: 3 of 11 events (trips only; relay FEEDER 12; 1 duplicate history row hidden)", text)
        self.assertIn("OVERVIEW", text)
        self.assertNotIn("EVENT DETAILS", text)
        none = app.build_report(self.events, self.rdb, self.err, self.paths, "", {"search": "zzz"})
        self.assertIn("No events match", none)

    def test_duplicate_note_when_target_hidden(self):
        text = app.build_report(self.events, self.rdb, self.err, self.paths, "", {"search": "Feeder12_history"})
        self.assertIn("Same event as the detailed report in Feeder12_AG_Zone1.cev (not shown in this view).", text)

    def test_detail_levels(self):
        std = app.build_report(self.events, self.rdb, self.err, self.paths, "", {"detail": "standard"})
        self.assertIn("EVENT DETAILS", std)
        self.assertNotIn("Element sequence", std)
        self.assertNotIn("Settings context", std)
        self.assertNotIn("SEQUENTIAL EVENTS RECORDER", std)

    def test_csv(self):
        import csv as _csv
        rows = list(_csv.reader(io.StringIO(app.report_csv(self.events, self.rdb, {"show": "review"}))))
        self.assertEqual(rows[0], app.CSV_COLUMNS)
        self.assertEqual(len(rows) - 1, len(self.view(show="review")[0]))
        f9 = next(r for r in rows[1:] if r[3] == "FEEDER 9")
        self.assertEqual((f9[10], f9[12], f9[14], f9[15], f9[16]), ("116", "3689", "8.00", "Low", "5"))

    def test_choices(self):
        c = app.view_choices(self.events, self.rdb)
        self.assertEqual((c["counts"]["all"], c["counts"]["notrip"]), (11, 1))
        self.assertIn(("FEEDER 12", 5), c["relays"])


class Updater(unittest.TestCase):
    def test_version_compare(self):
        self.assertGreater(app.version_tuple("v1.10.0"), app.version_tuple("1.9.9"))
        self.assertEqual(app.version_tuple("v1.1.0"), app.version_tuple("1.1.0"))

    def test_release_lookup(self):
        exe = b"MZ" + b"x" * 500
        rel = {"tag_name": "v99.0.0", "body": "notes", "html_url": "",
               "assets": [{"name": app.EXE_ASSET_NAME, "browser_download_url": "EXE",
                           "digest": "sha256:" + hashlib.sha256(exe).hexdigest()}]}

        class R(io.BytesIO):
            headers = {}

            def __enter__(self):
                return self

            def __exit__(self, *a):
                pass

        orig = app._http_get
        app._http_get = lambda url, **k: R(json.dumps(rel).encode() if "api.github" in url else exe)
        try:
            info = app.check_for_update()
            self.assertEqual(info["version"], "99.0.0")
            with tempfile.TemporaryDirectory() as d:
                digest = app.download_file("EXE", os.path.join(d, "x.exe"))
            self.assertEqual(digest, info["sha256"])
            rel["tag_name"] = "v" + app.VERSION
            self.assertIsNone(app.check_for_update())
        finally:
            app._http_get = orig


class RealFileCases(unittest.TestCase):
    """One sub-test per tests/fixtures/<case>/expected.json."""

    def test_cases(self):
        cases = sorted(d for d in os.listdir(FIXTURES)
                       if os.path.isfile(os.path.join(FIXTURES, d, "expected.json"))) \
            if os.path.isdir(FIXTURES) else []
        if not cases:
            self.skipTest("no real-file fixtures yet")
        for case in cases:
            folder = os.path.join(FIXTURES, case)
            with self.subTest(case=case), open(os.path.join(folder, "expected.json")) as f:
                exp = json.load(f)
                paths = app.expand_paths([folder])
                events, rdb, err = app.load_files(paths)
                self.assertFalse(err, err)
                evs = [e for e in events if e.kind in ("event", "history")]
                if "event_count" in exp:
                    self.assertEqual(len(evs), exp["event_count"])
                report = app.build_report(events, rdb, err, paths)
                for want in exp.get("report_contains", []):
                    self.assertIn(want, report)
                for i, ee in enumerate(exp.get("events", [])):
                    e = next((x for x in evs if x.source == ee["file"]), None) if "file" in ee else evs[i]
                    self.assertIsNotNone(e, ee)
                    for key in ("event_type", "location", "targets", "relay_id"):
                        if key in ee:
                            self.assertEqual(getattr(e, key), ee[key], f"{case} {key}")
                    s, label, how = app.match_settings(e, rdb)
                    cause = text(app.analyze_event(e, {**e.settings, **s}, how, label))
                    for want in ee.get("cause_contains", []):
                        self.assertIn(want, cause, f"{case}: summary should mention {want!r}")


